"""
Drift: a word that drifts.

A drift is a plant made of words. On each day it grows it adds one word, and
that word is a step from the word before it. What it may step to depends on
what has been written and thrown away in this garden: the heap, the humus,
the visitors' book, the notes at the gate. So a drift says different things
in different years, and grows richer as the garden is visited.


WHAT A SEED SAYS

    kind: drift
    word: rain              the word it begins from, or a short line (at most five words)
    steps: by spelling      how it goes from one word to the next (see below)
    breaks: often           how often it breaks a line: often, sometimes, seldom, or a
                            number (breaks: 5 is a new line about every fifth word;
                            breaks: 0 is never). No line runs past sixteen words.
    grows: when it rains    its weather: every day, when it rains, or under a waxing moon
    flowers: autumn         the season it flowers in (spring, summer, autumn, winter)
    colour: blue            the ink of its flowers: one of the plate's inks (red,
                            dark-red, pink, pale-pink, orange, yellow, blue, violet,
                            brown, white, black, grey) or #rrggbb. It is read
                            forgivingly ("Pale pink", "blue, like the sky"); a colour
                            the plate has no ink for is drawn violet. Green is kept
                            for what is new, so no drift flowers green.

and, if wanted:

    leaf: downy             downy or waxy (see QUALITIES)
    stem: brittle           (see QUALITIES)
    scent: night            dusk or night: the moths come to its flowers
    variety: <a name>       carried on by its own seed, dropped by a cross

The three ways of stepping:

    by succession   a word that followed this one somewhere in the soil. A drift
                    of this kind walks through what others wrote, a pair of words
                    at a time.
    by spelling     a word one letter away: one letter changed, added or taken
                    out (rain, rail, sail, soil).
    by sound        a word that rhymes with this one, or ends as it does; now and
                    then one that only keeps its vowel or its last consonants,
                    which is how sounds slide from one family into the next.

Wherever there is a choice, a word someone wrote in this garden weighs three
times as much as one the drift carries of its own, and a word it has said
lately weighs little. When the soil is thin, or has nothing to follow, the
drift steps by spelling among its own words: the words of its body, and its
stock, which is the words of its seed and a small hoard of plain words every
drift carries (HOARD, at the foot of this file). It takes only words the
garden can letter. If no word is one letter away, it takes one that ends as
this one does; if there is none of those either, it goes back to its seed
word.


HOW IT GROWS

At most one word a day. Its weather decides which days may be growing days:

    every day            any day; more often when it is warm and bright, so a
                         drift in full light says more than one under the wall
    when it rains        only a day with a millimetre of rain or more in its bed
                         (a wet bed keeps more of the rain: the pond's edge rains
                         more than the stones do); snow is not rain
    under a waxing moon  only from the new moon to the full, about half of each
                         month, and more often on warm bright days among them

No drift grows on a frost night, unless its leaf is downy. Ground made rich
(manure, a pony) quickens it. When the ground is dust dry it cannot reach
the soil (unless its leaf is waxy) and steps among its own words.

A drift lives some years. After its fifth, on a winter day, now and then, it
says its last word and withers. Its body stays where it stood, readable,
until the days carry it to the heap; there it rots, and its words go back
into the soil that the other drifts feed on.

The almanac hears of it seldom: when it comes into flower, when a frost
closes its flowers, when it first takes a word from the soil, when it comes
home to its seed word after a long way, when it finds no way on and goes
back to its seed word, when it comes up again after being cut to nothing,
when a creature eats something it will miss (see the end of FLOWERS AND
SEED), and when it withers. (Its flowers closing at the end of their
season, and its oldest season falling away, are only the calendar
speaking; the almanac is not told.)


THE BODY

The body is the drift itself: lines of words under season headings, the way
it grew them.

    autumn 2026
    rain
    rail sail* soil soul
    foul fowl

    winter 2026
    howl

A heading ("winter 2026") is written on the first day of each season, even
if nothing grows in it: a heading with no words under it is a season in
which the drift said nothing. Winter is named by the year it began in. A word
followed by * is in flower. The last word of the last line is the growing
tip: the next word will step from it.

It never repeats a line: a line that would say what an earlier line says is
not ended until it says something new. A drift keeps eight seasons of
itself; when a ninth begins, its oldest season falls away.


CUTTING

A drift is soft to the hand. Its body is plain words and parts anywhere: cut
a word, a line or a season, and it goes on from whatever word is last. Write
a word of your own at the end and it will go on from yours: from then on it
steps from your word as from its own, though the plate marks it as found (a
filled dot), not as of its stock. Cut it all away and it comes up again from
its seed. A body a hand has made enormous is shed from the top, the oldest
lines first, down to 1,600 words or 40,000 characters.


QUALITIES

    leaf: downy     it goes on growing through frost down to -4 °C, and its flowers
                    are not closed by it; slugs find it rough and take half as much.
    leaf: waxy      it keeps drawing on the soil in a drought. Any other drift, when
                    the ground is dust dry, can reach only its own words.
    stem: brittle   a windy day snaps its line: on such a day its new word begins
                    a new line.
    scent           cannot be drawn. It lives in the seed, and the moths read it there.


FLOWERS AND SEED

In its flowering season, on a mild day, the word it grows may open as a
flower (marked *). Seven at most are open at once. They close when the
season ends, or on a frost night. Bees and moths carry pollen between drifts
in flower. A drift sets no seed until it is about four months old, so a
seedling's first flowers are only flowers. After that, a drift that was
brought pollen now and then drops a crossed seed (at most about once in a
hundred and twenty such days, less with few flowers open): its word is two
words, one of this drift's flowers and one of the other's (a flower of the
other if it stands in this bed, else its seed word), its ways are taken now
from one parent and now from the other, and its colour is the two colours
blended. A drift in flower that was brought no pollen, more rarely still,
drops a seed of its own: a word it said in flower, with its parent's ways
and variety. Such a seedling is named after its word.

A bite (slugs, or a grazing pony) takes words from the end of the last
line: that is its soft growth. The drift goes on from what is left. Under
the wall the slugs come most wet nights, mostly for a single word, and most
of their bites are quiet. The almanac (and the drift's rings, which hear the
same) is told of a bite only when it costs the drift something: an open
flower ("slugs ate sail, in flower"), two words or more at once ("slugs ate
touch and peach"), a word of four letters or more that it found in the soil
and now has nowhere else ("slugs ate hedgehog"), or a crop, which is what
a pony takes.


THE PLATE

Each row is a season, oldest at the top, its name at the left, level with
its rule. Along the row stand the words of that season in the order they
grew, one to a word of the scale bar: a long row is a season in which it
said a great deal, a short one a season it mostly kept quiet, and "nothing
grew" a season with a heading and no words. The rows take the plate's
width; the scale bar measures only across.

    the height of a word      how many letters would have to change to make it one
                              of its seed words again. The row's rule is 0 letters.
                              The ruler at the left of each row has a tick for every
                              letter (longer and darker at 5 and 10), and the number
                              at its top says how many letters it holds. Rows are
                              drawn as tall as the plate has room for, so a letter
                              may be taller or shorter than a word is wide: read
                              heights against the ruler. A word more than twelve
                              letters off is drawn at twelve, with a small ^ over it.
    a line between two dots   the two words stand in one line of the body
    a slash under the rule    a line break: the next word began a new line. Beside a
                              circled word or a flower it hangs lower, clear of it.
    a ring                    a word of its stock: its seed's words, or its hoard
    a filled dot              any other word: one it found in the soil of this garden,
                              or one a hand wrote into it
    a circle round a dot      one of its seed words: where it began, or where it came
                              home. Seed words side by side share one long circle.
    a coloured ring           a flower, in its colour, edged a shade darker, with
      round a dot             the word's own dot at its heart
    green                     what has grown since the last visit, lettered in green too
    the rule itself           plain; doubled for a waxy leaf; broken into dashes for a
                              brittle stem; stippled for a downy leaf

The words are lettered where there is room, in this order: the newest word
(larger), the first word it still has, every homecoming, the farthest word
of each season, the flowers, what is new since the last visit, then the
first words of lines and as many others as fit. A word is lettered above
its dot or below it (the ones that matter most may go beside it), and never
over the rule, a slash, or a line between two words, so a gap in a line is
never made by lettering: where one word follows another there is a line.

The caption says how many words and lines it has, how far it has gone and
how often it came home (the seed words it began from are not counted as a
return), and how many of its words came from outside its stock: each time
such a word stands in the body, as the filled dots do, and how many
different words those are.

Standard library and hands only. Nothing here raises on a garbled body or seed.
"""

import math
import re

import hands

KIND = "drift"

SEASONS = ("spring", "summer", "autumn", "winter")
KEEP_SEASONS = 8            # seasons a drift keeps of itself (it grows at most a word a day: some 90 a season)
LINE_MOST = 16              # a line this long is ended whatever the temperament
WORDS_MOST = 1600           # a body written longer than this by hand is shed from the top
CHARS_MOST = 40_000         # and so is one longer than this
WORD_MOST = 24              # a longer word is not a word a drift can step from: from one, it goes home
TALLEST = 12                # letters from home drawn on the plate; a word farther away is drawn at 12, capped
HOME_AFTER = 20             # a homecoming after this many words away is told in the almanac
OPEN_MOST = 7               # flowers open at once
SEEDS_FROM = 120            # days old before it sets any seed
CROSSED = 0.002             # chance a day, for each open flower, of a crossed seed when drift pollen was brought
CROSSED_MOST = 0.008        # ... but never more than this in a day. (A drift is in flower all its season, with up
                            # to seven open: at 3% a day, sixteen drifts were fifty-seven in two years.)
OWN_SEED = 0.001            # chance a day, for each open flower, of a seed of its own when no pollen came
OWN_SEED_MOST = 0.004
CROP_FROM = 0.25            # a bite this big is a crop (a pony's), and always told; a smaller one only if it costs
LIFE = 5 * 365              # days a drift lives before it may wither
WITHERS = 1.0 / 120         # after that, its chance on each winter day
UNIT_PX = 44.0              # the most pixels one word may take on the plate
LABELS_MOST = 150           # words lettered on one plate, at most (where they find room)
LEADER = "#aaa69c"          # the tick from a word's dot to its lettering, where words stand close
BREAKS = (("often", 0.30), ("sometimes", 0.15), ("now and then", 0.15), ("seldom", 0.06), ("rarely", 0.06))
KEPT = ("steps", "breaks", "grows", "flowers", "colour", "leaf", "stem", "scent", "variety")
PALETTE = ("red", "dark-red", "pink", "pale-pink", "orange", "yellow", "blue", "violet", "brown", "white", "black", "grey")
SAID_AS = {"gray": "grey", "purple": "violet", "mauve": "violet", "crimson": "dark-red", "scarlet": "red",
           "rose": "pink", "rouge": "red", "bleu": "blue", "jaune": "yellow", "blanc": "white", "blanche": "white",
           "noir": "black", "noire": "black", "brun": "brown", "gris": "grey"}
APOSTROPHE = chr(0x2019)
_DAGGER = chr(0x2020)       # a body whose first line begins with it is dead
LETTERS = "abcdefghijklmnopqrstuvwxyz" + "".join(chr(c) for c in (0xE9, 0xE8, 0xEA, 0xE0, 0xE7, 0xF9, 0xE2, 0xEE, 0xF4, 0xFB, 0xEB, 0xEF))
VOWELS = "aeiou" + "".join(chr(c) for c in (0xE9, 0xE8, 0xEA, 0xE0, 0xF9, 0xE2, 0xEE, 0xF4, 0xFB, 0xEB, 0xEF))

_HEAD = re.compile(r"^\s*(spring|summer|autumn|winter)\s+(\d{4})\b", re.IGNORECASE)
_WORD = re.compile(r"([^\W\d_]+(?:['\-" + APOSTROPHE + r"][^\W\d_]+)*)(\*?)")
_LETTERABLE = re.compile("^[" + LETTERS + "]+(?:['-][" + LETTERS + "]+)*$")
_MARK = re.compile(r"(?<=[^\W\d_])\*+")
_CLAUSES = re.compile(r"[.!?;:()\[\]{}|]+")


# ============================================================ the seed

class _Temper:
    """What a seed says about how a drift lives, read forgivingly."""

    def __init__(self, seed):
        seed = seed if isinstance(seed, dict) else {}
        said = hands.line(seed, "steps", "").lower()
        if "succe" in said or "follow" in said:
            self.steps = "succession"
        elif "sound" in said or "rhym" in said or "ending" in said:
            self.steps = "sound"
        else:
            self.steps = "spelling"
        said = hands.line(seed, "breaks", "").lower()
        self.breaks = 0.15
        if re.search(r"\d", said):
            every = hands.num(seed, "breaks", 6, 0, 50)
            self.breaks = 0.0 if every < 1 else 1.0 / max(1.25, every)
        else:
            for name, chance in BREAKS:
                if name in said:
                    self.breaks = chance
                    break
        said = hands.line(seed, "grows", "").lower()
        if "rain" in said or "wet" in said or "pluie" in said:
            self.grows = "rain"
        elif "moon" in said or "lune" in said:
            self.grows = "moon"
        else:
            self.grows = "day"
        self.flowers = hands.word(seed, "flowers", "summer", SEASONS)
        self.colour = _ink(hands.line(seed, "colour", "") or hands.line(seed, "color", ""))
        self.leaf = hands.word(seed, "leaf", "", ("downy", "waxy"))
        self.brittle = hands.word(seed, "stem", "", ("brittle",)) == "brittle"


def _ink(said) -> str:
    """The ink a colour line names: a plate ink's name or '#rrggbb', read once, the same for the plate and for crossing.

    'Blue', 'pale pink', 'Dark-Red', 'blue, like the sky' and '#2563C0' are
    all understood: the first word (or pair of words) on the line that names
    an ink is taken. A line that names none gives violet.
    """
    tokens = re.findall(r"#[0-9a-f]{6}(?![0-9a-z])|#[0-9a-f]{3}(?![0-9a-z])|[^\W\d_]+", str(said or "").lower())
    for i, token in enumerate(tokens):
        if token.startswith("#"):
            return token if len(token) == 7 else "#" + "".join(c + c for c in token[1:])
        if i + 1 < len(tokens) and token + "-" + tokens[i + 1] in PALETTE:
            return token + "-" + tokens[i + 1]
        token = SAID_AS.get(token, token)
        if token in PALETTE:
            return token
    return "violet"


def _home(seed, name=None) -> list:
    """The seed's words: where the drift began, and what 'home' means on its plate.

    A seed with no word in it begins from the first word of the plant's
    name; a plant with neither begins from 'word'.
    """
    words = [w for w, _ in _tokens(hands.line(seed if isinstance(seed, dict) else {}, "word", ""))]
    words = [w for w in words if _LETTERABLE.match(w) and len(w) <= WORD_MOST][:5]
    if words:
        return words
    named = [w for w, _ in _tokens(str(name or "").replace("-", " ")) if _LETTERABLE.match(w) and len(w) <= WORD_MOST]
    return named[:1] or ["word"]


def _tokens(line) -> list:
    """The words of a line, lower-cased, each with True if it is marked as a flower."""
    found = []
    for match in _WORD.finditer(str(line or "")):
        word = match.group(1).lower().replace(APOSTROPHE, "'")
        found.append((word, bool(match.group(2))))
    return found


# ============================================================ the body

class _Body:
    """A drift's body as lines: headings, lines of words, and whatever else a hand left.

    Every change is made to the text itself, so that what a hand wrote
    (a remark, a capital, a comma) stays as it was written.
    """

    def __init__(self, body):
        text = body if isinstance(body, str) else ""
        self.lines = text.lstrip(chr(0xFEFF)).replace("\r\n", "\n").replace("\r", "\n").split("\n")
        while self.lines and not self.lines[-1].strip():
            self.lines.pop()
        self._read()

    def _read(self):
        self.kinds, self.words = [], {}
        for i, line in enumerate(self.lines):
            stripped = line.strip()
            if not stripped:
                self.kinds.append("blank")
            elif stripped.startswith("#") or stripped.startswith("†"):
                self.kinds.append("other")
            elif _HEAD.match(line):
                self.kinds.append("head")
            else:
                tokens = _tokens(line)
                if tokens:
                    self.kinds.append("words")
                    self.words[i] = tokens
                else:
                    self.kinds.append("other")

    def text(self) -> str:
        return "\n".join(self.lines).strip("\n") + "\n" if any(l.strip() for l in self.lines) else ""

    # ---- looking

    def word_lines(self) -> list:
        return [i for i, kind in enumerate(self.kinds) if kind == "words"]

    def flat(self) -> list:
        """Every word in order: (word, in flower, line index)."""
        return [(w, f, i) for i in self.word_lines() for w, f in self.words[i]]

    def count(self) -> int:
        return sum(len(tokens) for tokens in self.words.values())

    def last_word(self):
        lines = self.word_lines()
        return self.words[lines[-1]][-1][0] if lines else None

    def growing_line(self):
        """The index of the line the next word joins, or None if the next word begins a new line."""
        for i in range(len(self.kinds) - 1, -1, -1):
            if self.kinds[i] == "words":
                return i
            if self.kinds[i] == "head":
                return None
        return None

    def heads(self) -> list:
        return [i for i, kind in enumerate(self.kinds) if kind == "head"]

    def last_head(self) -> str:
        heads = self.heads()
        if not heads:
            return ""
        found = _HEAD.match(self.lines[heads[-1]])
        return "%s %s" % (found.group(1).lower(), found.group(2))

    def in_this_season(self) -> int:
        heads = self.heads()
        start = heads[-1] if heads else -1
        return sum(len(self.words[i]) for i in self.word_lines() if i > start)

    def flowers(self) -> list:
        return [w for w, f, _ in self.flat() if f]

    def repeats(self, i) -> bool:
        """Would line i, ended now, say what another line already says?"""
        mine = tuple(w for w, _ in self.words.get(i, ()))
        return any(tuple(w for w, _ in self.words[j]) == mine for j in self.word_lines() if j != i)

    # ---- changing

    def add_head(self, label):
        if self.lines:
            self.lines.append("")
        self.lines.append(label)
        self._read()

    def add_word(self, word, flower, new_line):
        token = word + ("*" if flower else "")
        at = None if new_line else self.growing_line()
        if at is None:
            self.lines.append(token)
        else:
            self.lines[at] = self.lines[at].rstrip() + " " + token
        self._read()

    def close_flowers(self) -> int:
        shut = 0
        for i in self.word_lines():
            line, n = _MARK.subn("", self.lines[i])
            if n:
                self.lines[i], shut = line, shut + n
        if shut:
            self._read()
        return shut

    def take_from_end(self, k) -> list:
        """Take k words off the end of the last line. Returns them in order, each with True if it was in flower."""
        lines = self.word_lines()
        if not lines or k <= 0:
            return []
        i = lines[-1]
        spans = list(_WORD.finditer(self.lines[i]))       # the same words as self.words[i], found the same way
        k = min(k, len(spans))
        taken = list(self.words[i][len(spans) - k:])
        rest = self.lines[i][:spans[len(spans) - k].start()].rstrip()
        if _tokens(rest):
            self.lines[i] = rest
        else:
            del self.lines[i]
        self._read()
        return taken

    def shed(self) -> int:
        """Let the oldest seasons fall away (and, for a body grown huge by hand, the oldest lines). Returns words shed.

        A body over its bounds is cut in one pass from the top: the oldest
        lines are counted off until what is left is within WORDS_MOST and
        CHARS_MOST, and the body is read again once. (Cut a line at a time,
        reading the body again after each, a hand's 3,000 short lines took
        the better part of a minute, and the ground set every drift aside.)
        The last line of words always stays, and if the cut took the heading
        of the season it left off in, that heading is written again on top.
        """
        before = self.count()
        heads = self.heads()
        if len(heads) > KEEP_SEASONS:
            self.lines = self.lines[heads[len(heads) - KEEP_SEASONS]:]
            self._read()
        words, size = self.count(), self.size()
        if words > WORDS_MOST or size > CHARS_MOST:
            lines = self.word_lines()
            last = lines[-1] if lines else len(self.lines) - 1
            cut, season = 0, None
            while cut < last and (words > WORDS_MOST or size > CHARS_MOST):
                words -= len(self.words.get(cut, ()))
                size -= len(self.lines[cut]) + 1
                if self.kinds[cut] == "head":
                    season = self.lines[cut]
                cut += 1
            kept = self.lines[cut:]
            first = next((i for i, line in enumerate(kept) if line.strip()), None)
            if season is not None and first is not None and not _HEAD.match(kept[first]):
                found = _HEAD.match(season)
                kept = ["%s %s" % (found.group(1).lower(), found.group(2))] + kept[first:]
            self.lines = kept
            self._read()
        lines = self.word_lines()
        if lines and (self.count() > WORDS_MOST or self.size() > CHARS_MOST):
            i = lines[-1]                                    # one line, written enormous by a hand: keep its end
            spans = list(_WORD.finditer(self.lines[i]))
            keep = [m for m in spans[-WORDS_MOST:] if len(m.group(0)) <= CHARS_MOST // 4]
            self.lines[i] = self.lines[i][keep[0].start():] if keep else "word"
            if self.size() > CHARS_MOST:
                self.lines[i] = " ".join(m.group(0)[:WORD_MOST] for m in keep[-200:]) or "word"
            self._read()
        return max(0, before - self.count())

    def size(self) -> int:
        return sum(len(line) + 1 for line in self.lines)


def _season_label(ctx) -> str:
    """'autumn 2026'. Winter is named by the year it began in."""
    date = getattr(ctx, "date", None)
    season = getattr(getattr(ctx, "sky", None), "season", None)
    if season not in SEASONS:
        month = getattr(date, "month", 9)
        season = ("winter", "winter", "spring", "spring", "spring", "summer",
                  "summer", "summer", "autumn", "autumn", "autumn", "winter")[max(0, min(11, month - 1))]
    year = getattr(date, "year", 2026)
    if getattr(date, "month", 6) in (1, 2):
        year -= 1
    return "%s %d" % (season, year)


# ============================================================ the words it can reach

def _hoard_words() -> frozenset:
    return frozenset(w for w in HOARD.split() if _LETTERABLE.match(w) and len(w) >= 3)


def _is_vowel(word, i) -> bool:
    return word[i] in VOWELS or (word[i] == "y" and i > 0)


def _sound(word) -> tuple:
    """(rime, coda, vowel, ending) of a word as it is spelled.

    The rime is the last vowel group and what follows it (light -> ight,
    rain -> ain). A silent e after a consonant goes with the syllable before
    it (stone -> one). The coda is what follows the vowel, the vowel is the
    vowel group alone, and the ending is the last two letters.
    """
    region, tail = word, ""
    if len(word) > 2 and word[-1] == "e" and not _is_vowel(word, len(word) - 2):
        region, tail = word[:-1], "e"
    i = len(region) - 1
    while i >= 0 and not _is_vowel(region, i):
        i -= 1
    if i < 0:
        return word, word, "", word[-2:]
    j = i
    while j > 0 and _is_vowel(region, j - 1):
        j -= 1
    return region[j:] + tail, region[i + 1:] + tail, region[j:i + 1], word[-2:]


def _sound_index(words) -> tuple:
    """Four indexes of a set of words: by rime, by coda, by vowel, by ending."""
    index = ({}, {}, {}, {})
    for word in sorted(words):
        if len(word) < 3:
            continue
        for place, key in zip(index, _sound(word)):
            if key:
                place.setdefault(key, []).append(word)
    return index


class _Text:
    """One text of the soil, read once: its words, and which word followed which."""

    def __init__(self, where, text):
        humus = where.replace("\\", "/").endswith("compost/humus")
        vocab, follows, before = set(), {}, None
        for line in text.split("\n"):
            if humus or not line.strip():
                before = None                        # the humus is lines scattered at random: each is a text of its own
            clauses = _CLAUSES.split(line)
            for n, clause in enumerate(clauses):
                for word, _ in _tokens(clause):
                    if not _LETTERABLE.match(word) or len(word) > 18:
                        before = None
                        continue
                    vocab.add(word)
                    if before is not None and before != word:
                        follows.setdefault(before, []).append(word)
                    before = word
                if n < len(clauses) - 1:
                    before = None                    # nothing follows across the end of a sentence
        self.vocab = frozenset(vocab)
        self.follows = follows


class _Soil:
    """Everything a drift may feed on today, gathered from ctx.soil."""

    def __init__(self, texts):
        self.texts = texts
        self.vocab = frozenset().union(*(t.vocab for t in texts)) if texts else frozenset()
        self._sound = None

    def followers(self, word) -> dict:
        counts = {}
        for text in self.texts:
            for after in text.follows.get(word, ()):
                counts[after] = counts.get(after, 0) + 1
        return counts

    def sound(self) -> tuple:
        if self._sound is None:
            self._sound = _sound_index(self.vocab)
        return self._sound


HOARD_SOUND = None
_TEXTS = {}                  # (where, length, hash) -> _Text: a text is read again only when it changes
_SOIL = [None, _Soil([])]    # [the key of the soil last gathered, that soil]
_EMPTY = _Soil([])


def _soil(ctx) -> _Soil:
    """The soil as a drift sees it. Kept between days while it has not changed; never raises."""
    try:
        texts = [(str(where), text) for where, text in ctx.soil.texts() if isinstance(text, str)]
    except Exception:
        return _EMPTY
    key = tuple((where, len(text), hash(text)) for where, text in texts)
    if _SOIL[0] == key:
        return _SOIL[1]
    kept = {}
    for (where, text), mark in zip(texts, key):
        kept[mark] = _TEXTS.get(mark) or _Text(where, text)
    _TEXTS.clear()
    _TEXTS.update(kept)
    _SOIL[0], _SOIL[1] = key, _Soil([kept[mark] for mark in key])
    return _SOIL[1]


def _edits(word) -> set:
    """Every string one letter away from a word: a letter changed, added or taken out."""
    near = set()
    for i in range(len(word) + 1):
        head, tail = word[:i], word[i:]
        for c in LETTERS:
            near.add(head + c + tail)
            if tail:
                near.add(head + c + tail[1:])
        if tail:
            near.add(head + tail[1:])
    near.discard(word)
    return near


def _choose(weighted, rng):
    """One word from {word: weight}, by the day's dice. The words are sorted first, so the dice decide, not the order."""
    items = sorted((w, v) for w, v in weighted.items() if v > 0)
    total = sum(v for _, v in items)
    if not items or total <= 0:
        return None
    point = rng.random() * total
    for word, weight in items:
        point -= weight
        if point < 0:
            return word
    return items[-1][0]


def _weigh(candidates, soil_vocab, recent, seen):
    """Weights for the words a drift could step to: soil words count three, lately said words little."""
    weights = {}
    for word in candidates:
        if word in recent:
            continue
        weight = 3.0 if word in soil_vocab else 1.0
        if word in seen:
            weight *= 0.2
        weights[word] = weight
    return weights


def _by_spelling(word, own, soil_vocab, recent, seen):
    near = _edits(word)
    found = {w for w in near if len(w) >= 3 and (w in own or w in soil_vocab)}
    return _weigh(found, soil_vocab, recent, seen)


def _by_sound(word, own, soil, soil_open, recent, seen, rng):
    """Rhyme first; then a shared ending; now and then only the last consonants, or only the vowel."""
    global HOARD_SOUND
    if HOARD_SOUND is None:
        HOARD_SOUND = _sound_index(HOARD_SET)
    keys = _sound(word)
    extra = _sound_index(own - HOARD_SET)
    indexes = [HOARD_SOUND, extra] + ([soil.sound()] if soil_open else [])
    tiers = []
    for place in range(4):
        found = set()
        for index in indexes:
            found.update(index[place].get(keys[place], ()))
        tiers.append(found)
    rime, coda, vowel, ending = tiers
    ending -= rime
    coda = {w for w in coda if _sound(w)[2] != keys[2]}
    vowel = {w for w in vowel if _sound(w)[1] != keys[1]}
    vocab = soil.vocab if soil_open else frozenset()
    weighted = [(0.50, _weigh(rime - {word}, vocab, recent, seen)),
                (0.18, _weigh(ending - {word}, vocab, recent, seen)),
                (0.12, _weigh(coda - {word}, vocab, recent, seen)),
                (0.20, _weigh(vowel - {word}, vocab, recent, seen))]
    weighted = [(share, w) for share, w in weighted if w]
    if not weighted:
        return {}
    point = rng.random() * sum(share for share, _ in weighted)
    for share, w in weighted:
        point -= share
        if point < 0:
            return w
    return weighted[-1][1]


def _step(word, temper, home, body_words, ctx):
    """The next word, and where it came from: 'soil', 'own' or 'home'."""
    rng = ctx.rng
    sky = getattr(ctx, "sky", None)
    soil = _soil(ctx)
    dry = _num(sky, "wet", 0.5) < 0.05 and _num(sky, "rain", 0.0) <= 0
    soil_open = temper.leaf == "waxy" or not dry
    vocab = soil.vocab if soil_open else frozenset()
    own = HOARD_SET | frozenset(w for w in body_words + home if _LETTERABLE.match(w))
    recent = set(body_words[-4:])
    seen = set(body_words[-40:])
    weights = {}
    if temper.steps == "succession" and soil_open:
        counts = soil.followers(word)
        weights = {w: c * (0.3 if w in seen else 1.0) for w, c in counts.items() if w != word}
    elif temper.steps == "sound":
        weights = _by_sound(word, own, soil, soil_open, recent, seen, rng)
    if not weights:
        weights = _by_spelling(word, own, vocab, recent, seen)
    if not weights and temper.steps != "sound":
        weights = _by_sound(word, own, soil, soil_open, recent, seen, rng)
    chosen = _choose(weights, rng)
    if chosen is None:
        for w in home:
            if w != word:
                return w, "home"
        starting = sorted(w for w in HOARD_SET if w[0] == word[:1] and w not in recent) or sorted(HOARD_SET)
        return rng.choice(starting), "home"
    return chosen, ("soil" if chosen in vocab else "own")


# ============================================================ the days

def _num(thing, name, default):
    """A number from the sky (or anything), never raising."""
    try:
        value = float(getattr(thing, name))
    except Exception:
        return default
    return value if value == value else default


def _chance(temper, sky, bed) -> float:
    """How likely the drift is to grow a word today, under this sky, in this bed."""
    tmin = _num(sky, "tmin", 8.0)
    if tmin < (-4.0 if temper.leaf == "downy" else 0.0):
        return 0.0
    if getattr(sky, "snow", False) and temper.leaf != "downy":
        return 0.0
    warm = min(1.0, _num(sky, "warmth", 5.0) / 8.0)
    lit = min(1.0, _num(sky, "light", 6.0) / 7.0)
    vigour = 0.5 * warm + 0.5 * lit
    rich = hands.num(bed if isinstance(bed, dict) else {}, "rich", 0.0, 0.0, 1.0)
    vigour = min(1.0, vigour * (1.0 + 0.6 * rich))
    if temper.grows == "rain":
        if _num(sky, "rain", 0.0) < 1.0 or getattr(sky, "snow", False):
            return 0.0
        return 0.55 + 0.45 * vigour
    if temper.grows == "moon":
        moon = _num(sky, "moon", 0.0)
        if not 0.02 < moon < 0.5:
            return 0.0
        return 0.3 + 0.6 * vigour
    return 0.15 + 0.8 * vigour


def sprout(seed, ctx) -> str:
    """A season heading, and the seed's words as the first line."""
    return "%s\n%s\n" % (_season_label(ctx), " ".join(_home(seed, getattr(ctx, "name", None))))


def day(body, seed, ctx):
    """One day: a new season's heading if one has begun, flowers closed by the season's end or a frost, and perhaps a word."""
    if hands.is_dead(body):
        return body, None
    temper = _Temper(seed)
    home = _home(seed, getattr(ctx, "name", None))
    drift = _Body(body)
    sky = getattr(ctx, "sky", None)
    rng = ctx.rng
    said = {}
    if not drift.words:
        if not drift.text():
            return sprout(seed, ctx), "came up again from its seed"
        if drift.last_head() != _season_label(ctx):
            drift.add_head(_season_label(ctx))
        drift.add_word(" ".join(home), False, True)
        drift.shed()
        return drift.text(), "came up again from its seed"
    label = _season_label(ctx)
    if drift.last_head() != label:
        drift.add_head(label)
    drift.shed()                                          # the oldest season falls away: the calendar, not news
    open_now = len(drift.flowers())
    season = getattr(sky, "season", None)
    if open_now and season != temper.flowers:
        drift.close_flowers()                             # the end of its flowering season: not news either
    elif open_now and _num(sky, "tmin", 8.0) < (-4.0 if temper.leaf == "downy" else 0.0):
        drift.close_flowers()
        said[4] = "frost closed its flowers"
    if _withers(ctx, season, rng):
        last = drift.last_word()
        drift.close_flowers()
        return (_DAGGER + " %s, withered after %d years\n" % (_iso(ctx), int(_num(ctx, "age", 0) // 365))
                + drift.text(), "said its last word, %s, and withered" % (last or "nothing")[:WORD_MOST])
    if rng.random() < _chance(temper, sky, getattr(ctx, "bed", {})):
        _grow(drift, temper, home, ctx, said)
        drift.shed()                                      # (a body a hand made enormous stays in bounds with its new word)
    return drift.text(), (said[min(said)] if said else None)


def _iso(ctx) -> str:
    try:
        return ctx.date.isoformat()
    except Exception:
        return "a day"


def _withers(ctx, season, rng) -> bool:
    """Whether today is its last: only after LIFE days, only in winter, and then only now and then."""
    return season == "winter" and _num(ctx, "age", 0) >= LIFE and rng.random() < WITHERS


def _grow(drift, temper, home, ctx, said) -> None:
    """One word: stepped from the last, perhaps on a new line, perhaps in flower."""
    rng, sky = ctx.rng, getattr(ctx, "sky", None)
    flat = [w for w, _, _ in drift.flat()]
    last = flat[-1]
    if len(last) > WORD_MOST:                             # no word is one letter from a word as long as that
        word, source = home[0], "home"
    else:
        word, source = _step(last, temper, home, flat, ctx)
    new_line = drift.growing_line() is None
    if not new_line:
        line = drift.growing_line()
        snaps = temper.brittle and _num(sky, "wind", 0.0) >= 4.0
        new_line = len(drift.words[line]) >= LINE_MOST or snaps or rng.random() < temper.breaks
        if new_line and drift.repeats(line):
            new_line = False                              # it never repeats a line: this one goes on until it is new
    opens = (getattr(sky, "season", None) == temper.flowers and _num(sky, "tmean", 10.0) >= 7.0
             and len(drift.flowers()) < OPEN_MOST and rng.random() < 0.3)
    had_flowers = bool(drift.flowers())
    drift.add_word(word, opens, new_line)
    if opens and not had_flowers:
        said[3] = "came into flower"
    if word in home:
        away = 0
        for earlier in reversed(flat):
            if earlier in home:
                break
            away += 1
        if away >= HOME_AFTER and len(flat) > away:
            said[2] = "came back to %s after %d words" % (word, away)
    if source == "soil" and len(word) >= 4 and word not in HOARD_SET and word not in home:
        if all(w in HOARD_SET or w in home or len(w) < 4 for w in flat):
            said[1] = "took its first word from the soil: %s" % word
    if source == "home" and word in home:
        said.setdefault(2, "found no way on from %s, and went back to %s" % (last, word))


# ============================================================ creatures, and seed

def flowers(body, seed, ctx) -> int:
    """How many of its words are open flowers today."""
    if hands.is_dead(body):
        return 0
    return len(_Body(body).flowers())


def bitten(body, seed, ctx, share, by):
    """A bite of this share of its soft growth: words off the end of its last line.

    Only a bite that costs the drift something is told (in its rings and the
    almanac, which hear the same lines): a crop (a bite of CROP_FROM or more:
    a grazing pony's), an open flower, two words or more at once, or a
    word of four letters or more that it found in the soil and that now stands
    nowhere else in it. A small bite of one plain word is quiet: the body
    changes, and the drift goes on from what is left. (With every bite told,
    the drifts under the north wall were a third of the almanac.)
    """
    if hands.is_dead(body):
        return body, None
    drift = _Body(body)
    lines = drift.word_lines()
    if not lines:
        return body, None
    try:
        share = min(1.0, max(0.0, float(share)))
    except (TypeError, ValueError):
        return body, None
    if share != share:
        return body, None
    spare = 0.5 if _Temper(seed).leaf == "downy" else 1.0
    want = share * len(drift.words[lines[-1]]) * spare
    k = int(want) + (1 if ctx.rng.random() < want - int(want) else 0)
    k = min(k, drift.count() - 1)
    if k <= 0:
        return body, None
    taken = drift.take_from_end(k)
    if not taken:
        return body, None
    words = [w for w, _ in taken]
    open_ = [w for w, flower in taken if flower]
    stock = HOARD_SET | frozenset(_home(seed, getattr(ctx, "name", None)))
    left = {w for w, _, _ in drift.flat()}
    missed = [w for w in words if len(w) >= 4 and w not in stock and w not in left]    # found, and now gone from it
    if share < CROP_FROM and len(words) < 2 and not open_ and not missed:
        return drift.text(), None
    by = " ".join(str(by or "something").split())[:40] or "something"
    said = "%s ate %s" % (by, _listed(words))
    if open_:
        if len(words) == 1:
            said += ", in flower"
        elif len(open_) == 1:
            said += ", %s in flower" % open_[0]
        else:
            said += ", %s in flower" % ("both" if len(words) == 2 else "all" if len(open_) == len(words)
                                         else "%s of them" % NUMBERS[min(len(open_), len(NUMBERS) - 1)])
    return drift.text(), said


NUMBERS = ("no", "one", "two", "three", "four", "five", "six", "seven", "many")


def _listed(words) -> str:
    words = list(words)
    if len(words) > 3:
        return "%s and %d more" % (", ".join(words[:2]), len(words) - 2)
    return words[0] if len(words) == 1 else ", ".join(words[:-1]) + " and " + words[-1]


def _own_seed(seed, word) -> dict:
    kept = {"kind": KIND, "word": word}
    for key in KEPT:
        if hands.line(seed, key, ""):
            kept[key] = hands.line(seed, key, "")
    kept["name"] = word
    return kept


def _donor(item):
    donor = getattr(item, "seed", None)
    if isinstance(donor, str):
        donor = hands.read_keys(donor)
    if not isinstance(donor, dict):
        donor = {}
    return donor, str(getattr(item, "where", "") or "another drift")


def _donor_word(donor, where, ctx) -> str:
    """A word of the pollen parent: one of its open flowers if it stands in this bed, else its seed word.

    A neighbour is the parent only if the pollen came from this bed: two
    beds may each hold a drift of the same name (a packet copied twice).
    """
    bed, _, name = where.replace("\\", "/").rpartition("/")
    mine = str(getattr(ctx, "where", "") or "").replace("\\", "/").rpartition("/")[0]
    if bed == mine:
        for other in getattr(ctx, "neighbours", None) or []:
            if getattr(other, "name", None) == name and getattr(other, "kind", None) == KIND:
                open_ = _Body(getattr(other, "body", "")).flowers()
                if open_:
                    return sorted(open_)[ctx.rng.randrange(len(open_))]
    return _home(donor, name)[-1]


def _crossed(seed, donor, where, mine, ctx) -> str:
    rng = ctx.rng
    theirs = _donor_word(donor, where, ctx)
    child = {"kind": KIND, "word": "%s %s" % (mine, theirs)}
    for key in ("steps", "breaks", "grows", "flowers", "leaf", "stem", "scent"):
        said = rng.choice((hands.line(seed, key, ""), hands.line(donor, key, "")))
        if said:
            child[key] = said
    child["colour"] = hands.mix(_Temper(seed).colour, _Temper(donor).colour, 0.5)
    child["name"] = "%s-%s" % (mine, theirs)
    child["from"] = "cross of %s × %s" % (getattr(ctx, "where", "a drift"), where)
    return hands.write_keys(child)


def cast(body, seed, ctx):
    """Seed dropped today, if any: now and then a cross when drift pollen was brought; more rarely, one of its own.

    Nothing before it is SEEDS_FROM days old. At most one seed a day. The
    chances are low because a drift flowers long: all its season, with up
    to seven open. At 35% a grain, in trial, drifts had filled every bed in
    a year and kept it; at 3% a day they still doubled each year. At these
    rates, in trial, sixteen drifts brought up ten in three years (three of
    them crosses) and no bed filled: a drift leaves one or two seedlings in
    its life.
    """
    if hands.is_dead(body) or _num(ctx, "age", SEEDS_FROM) < SEEDS_FROM:
        return []
    flowers = _Body(body).flowers()
    open_ = sorted(set(flowers))
    if not open_:
        return []
    rng = ctx.rng
    pollen = [item for item in list(getattr(ctx, "pollen", None) or [])[:40]
              if hands.word(_donor(item)[0], "kind", "") == KIND and _donor(item)[1] != getattr(ctx, "where", None)]
    if pollen:
        if rng.random() < min(CROSSED_MOST, CROSSED * len(flowers)):
            donor, where = _donor(pollen[rng.randrange(len(pollen))])
            return [_crossed(seed, donor, where, rng.choice(open_), ctx)]
        return []
    if rng.random() < min(OWN_SEED_MOST, OWN_SEED * len(flowers)):
        return [hands.write_keys(_own_seed(seed, rng.choice(open_)))]
    return []


def describe(body, seed, ctx) -> str:
    drift = _Body(body)
    n, lines = drift.count(), len(drift.word_lines())
    text = "%d word%s in %d line%s" % (n, "" if n == 1 else "s", lines, "" if lines == 1 else "s")
    if hands.is_dead(body):
        return "dead; it had said " + text
    open_ = len(drift.flowers())
    if open_:
        text += ", %d in flower" % open_
    last = drift.last_word()
    return text + (" · last word: %s" % last if last else "")


def size(body, seed) -> float:
    """For its dot on the plan: its words, six to a unit (about a line of them)."""
    return _Body(body).count() / 6.0


# ============================================================ the plate

def _distance(a, b) -> int:
    """How many letters must change (be changed, added or taken out) to turn a into b."""
    if a == b:
        return 0
    if len(a) < len(b):
        a, b = b, a
    before = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        now = [i]
        for j, cb in enumerate(b, 1):
            now.append(min(before[j] + 1, now[j - 1] + 1, before[j - 1] + (ca != cb)))
        before = now
    return before[-1]


def _rows(drift) -> list:
    """The seasons as rows, oldest first: [(label, [(word, in flower, line index, place in line), ...])]."""
    rows, label, words = [], None, []
    for i, kind in enumerate(drift.kinds):
        if kind == "head":
            if label is not None or words:
                rows.append((label or "", words))
            found = _HEAD.match(drift.lines[i])
            label, words = "%s %s" % (found.group(1).lower(), found.group(2)), []
        elif kind == "words":
            words += [(word, flower, i, k) for k, (word, flower) in enumerate(drift.words[i])]
    if label is not None or words:
        rows.append((label or "", words))
    folded = []
    for label, words in rows:                     # a season written long by hand is folded, a hundred words to a row
        for start in range(0, max(1, len(words)), 100):
            folded.append((label if start == 0 else label + " (on)", words[start:start + 100]))
    return folded


def _fresh(drift, left) -> set:
    """Which words, as (line index, place in line), have come since the last visit.

    A line that was there before is old however it stands now; the line
    that was growing then is old as far as it still reads the same.
    """
    if left is None:
        return {(i, k) for i in drift.word_lines() for k in range(len(drift.words[i]))}
    was = _Body(left)
    counts = {}
    for i in was.word_lines():
        key = tuple(w for w, _ in was.words[i])
        counts[key] = counts.get(key, 0) + 1
    tip = tuple(w for w, _ in was.words[was.word_lines()[-1]]) if was.word_lines() else ()
    fresh = set()
    for i in drift.word_lines():
        key = tuple(w for w, _ in drift.words[i])
        if counts.get(key, 0) > 0:
            counts[key] -= 1
            continue
        old = 0
        if tip:
            while old < min(len(key), len(tip)) and key[old] == tip[old]:
                old += 1
            if old:
                tip = ()                          # the growing line is found once
        fresh.update((i, k) for k in range(old, len(key)))
    return fresh


def draw(body, seed, ctx, pen) -> None:
    """The plate: a row for each season, each word a dot at its height in letters from home (see THE PLATE)."""
    pen.unit_name = "word, words"
    pen.unit_px_max = UNIT_PX
    pen.align = "center"
    drift = _Body(body)
    dead = hands.is_dead(body)
    temper = _Temper(seed)
    home = _home(seed, getattr(ctx, "name", None))
    rows = _rows(drift)[-(KEEP_SEASONS + 2):]
    if not any(words for _, words in rows):
        pen.note("nothing has grown yet")
        return
    fresh = set() if dead else _fresh(drift, getattr(ctx, "left", None))
    far = {}

    def away(word):
        """Letters from home, as drawn: at most TALLEST (beyond that a word is drawn there, with a ^ over it)."""
        if word not in far:
            far[word] = min(TALLEST + 1, min(_distance(word[:TALLEST * 3], h) for h in home))
        return min(far[word], TALLEST)
    away.far = far

    top = max(3, max(away(w[0]) for _, words in rows for w in words))
    longest = max(8, max(len(words) for _, words in rows))
    count = len(rows)
    try:
        measure = pen.canvas.text_width
        measure("a", 14)
    except Exception:
        measure = lambda s, size: 0.55 * size * len(s)

    box = getattr(pen, "box", None) or (60, 50, 840, 930)
    heads = [(label or "(no season)") for label, _ in rows]
    s, tall, gap_px = _layout(box, max(measure(head, 14) for head in heads) + 16.0, count, top, longest)
    px = 1.0 / s                                  # one pixel, in the drawing's units
    lead = max(1.3, 18.0 * px)                    # the ruler stands this far left of a row's first word
    row_h = top * tall + gap_px * px
    wood = "dead" if dead else "wood"
    plain = "dead" if dead else "ink"
    bloom = "dead" if dead else temper.colour
    edge = "dead" if dead else hands.mix(temper.colour, "#1a1a1a", 0.35)     # a flower's rim: pale ones need it
    ring = 4.5 if s >= 11 else max(3.0, 0.4 * s)  # a word's dot: a ring round clear paper, or filled
    solid = max(3.0, ring - 0.5)
    slash = 6.0 if s >= 12 else 3.0               # how wide a slash leans: narrower where the words stand close
    room = _Room()                                # the places no label may cover or cut, in pixels with y down
    wanted = []                                   # what would be lettered: see where it is gathered, below
    order = 0
    for r, (label, words) in enumerate(rows):
        base = (count - 1 - r) * row_h
        rule_y = -base * s                        # the rule's place on the page, in pixels (y down)
        end = max(len(words) - 0.5, 1.5)
        rx = -lead

        # The rule, in the texture of the plant's qualities. No word is lettered over it or its slashes.
        _rule(pen, -0.5, end, base, temper, "dead" if dead else "grey", px, r)
        room.add(-0.5 * s - 2, rule_y - 6, end * s + 2, rule_y + 17)

        # The ruler: a tick for each letter, longer and darker at 5 and 10, and at its top the letters it holds.
        pen.line(rx, base, rx, base + top * tall, 2, "faint")
        for k in range(top + 1):
            major = k > 0 and k % 5 == 0
            tick = (5 if major else 3) * px
            pen.line(rx - tick, base + k * tall, rx + tick, base + k * tall, 2, "grey" if major else "faint")
        top_y = rule_y - top * tall * s
        room.add(rx * s - 6, top_y - 3, rx * s + 6, rule_y + 3)
        head = heads[r]
        pen.label(rx - 9 * px, base - 5 * px, head, 14, plain, "end")
        room.add(rx * s - 12 - measure(head, 14), rule_y - 7, rx * s - 6, rule_y + 10)
        holds = "%d letters" % top if r == 0 else "%d" % top
        pen.label(rx - 9 * px, base + top * tall - 5 * px, holds, 14, "grey", "end")
        room.add(rx * s - 12 - measure(holds, 14), top_y - 7, rx * s - 6, top_y + 10)
        if not words:
            pen.label(end + 8 * px, base - 5 * px, "nothing grew", 14, "grey", "start")
            continue

        ys = [base + away(w[0]) * tall for w in words]
        points = [(k * s, -ys[k] * s) for k in range(len(words))]       # the dots on the page, in pixels (y down)
        new = [(line, place) in fresh for _, _, line, place in words]
        stock = [w[0] in HOARD_SET or w[0] in home for w in words]
        runs = _home_runs(words, away)                            # seed words, circled: [(first, last, radius)]
        circled = {k: radius for first, last, radius in runs for k in range(first, last + 1)}
        reach = [circled[k] + 1 if k in circled else (11.0 if words[k][1] else ring) for k in range(len(words))]

        # Slashes: a line break under the rule, hung lower where a circle or a flower comes down near it.
        for k in range(1, len(words)):
            if words[k][3] != 0:
                continue
            drop = 6.0                                            # clear of the rule, even a doubled one
            for j in (k - 1, k):
                if s / 2.0 < reach[j] + slash / 2.0 + 2.0:
                    drop = max(drop, reach[j] - (ys[j] - base) * s + 3.0)
            pen.line(k - 0.5 - slash / 2 * px, base - (drop + 9) * px, k - 0.5 + slash / 2 * px, base - drop * px, 2, plain)
            room.add((k - 0.5) * s - slash / 2 - 2, rule_y + drop - 1, (k - 0.5) * s + slash / 2 + 2, rule_y + drop + 10)

        # The lines between words that stand in one line of the body.
        for k in range(1, len(words)):
            if words[k][3] > 0:
                pen.line(k - 1, ys[k - 1], k, ys[k], 2.5, "fresh" if new[k] else wood)
                room.stroke((k - 1) * s, -ys[k - 1] * s, k * s, -ys[k] * s)

        # The dots, over the lines: flowers first, then clear paper for the rings, the seed circles, the words.
        for k, (word, flower, _, _) in enumerate(words):
            if flower:
                pen.dot(k, ys[k], 10, bloom)
                pen.dot(k, ys[k], 10, edge, filled=False, weight=2)
        for k, (word, flower, _, _) in enumerate(words):
            if flower or stock[k]:
                pen.dot(k, ys[k], (ring if stock[k] else solid) + (1.25 if flower else 0.0), "paper")
        for first, last, radius in runs:
            if first == last or s >= 2 * radius + 2:
                for k in range(first, last + 1):
                    pen.dot(k, base, radius, plain, filled=False, weight=2)
            else:                                                 # side by side: one long circle round the run
                rr = radius * px
                pen.arc(first, base, rr, 90, 270, 2, plain)
                pen.arc(last, base, rr, -90, 90, 2, plain)
                pen.line(first, base + rr, last, base + rr, 2, plain)
                pen.line(first, base - rr, last, base - rr, 2, plain)
        for k, (word, flower, line, place) in enumerate(words):
            ink = "fresh" if new[k] else wood
            if stock[k]:
                pen.dot(k, ys[k], ring, ink, filled=False, weight=2)
            else:
                pen.dot(k, ys[k], solid, ink)
            capped = far[word] > TALLEST
            if capped:                                            # farther than the ruler: a ^ over it
                c = reach[k] + 2
                pen.polyline([(k - 4 * px, ys[k] + c * px), (k, ys[k] + (c + 4) * px), (k + 4 * px, ys[k] + c * px)], 2, plain)
            room.add(k * s - reach[k] - 1, -ys[k] * s - reach[k] - (7 if capped else 1),
                     k * s + reach[k] + 1, -ys[k] * s + reach[k] + 1)

        # What would be lettered, and how much it matters. A run of seed words is lettered as one.
        farthest = max(away(w[0]) for w in words)
        run_of = {first: last for first, last, _ in runs if last > first}
        k = 0
        while k < len(words):
            last = run_of.get(k, k)
            members = range(k, last + 1)
            word, flower = words[k][0], any(words[j][1] for j in members)
            order += 1
            if r == count - 1 and last == len(words) - 1:
                rank = 0                          # the growing tip
            elif r == 0 and k == 0:
                rank = 1                          # the first word it still has
            elif away(word) == 0:
                rank = 2                          # a homecoming
            elif away(word) == farthest:
                rank = 3                          # the farthest it went that season
            elif flower:
                rank = 4
            elif new[k]:
                rank = 5
            elif words[k][3] == 0:
                rank = 6                          # the first word of a line
            else:
                rank = 7
            shown = " ".join(w if len(w) <= WORD_MOST else w[:WORD_MOST - 1] + "…" for w in (words[j][0] for j in members))
            fresh_ink = any(new[j] for j in members)
            # The newest first among the fresh; the rest in turn along every row (each row's first words, then
            # its second...), so that the rows share the lettering and the oldest do not take it all.
            turn = -order if fresh_ink else (k * 16 + r if rank >= 6 else order)
            wanted.append((rank, turn, (k + last) / 2.0, ys[k], shown, 16 if rank == 0 else 14,
                           "fresh" if fresh_ink else plain, max(reach[j] for j in members),
                           any(far[words[j][0]] > TALLEST for j in members), away(word) == 0, rule_y, points, members))
            k = last + 1

    placed = 0
    for rank, _, x, y, shown, size, ink, reach, capped, on_rule, rule_y, points, members in sorted(
            wanted, key=lambda w: (w[0], w[1])):
        if placed >= LABELS_MOST:
            break
        width = measure(shown, size) + 4
        X, Y = x * s, -y * s
        lift = 6.0 if capped else 0.0                         # room for the ^ over a word farther than the ruler

        def crowded(above):
            """Would lettering here be read as another word's? Where words stand close, and another dot as high
            as this one (or as low, for lettering below) lies under the lettering's width."""
            return s < 14.0 and any(abs(qx - X) < width / 2 + 2 and ((qy <= Y + 2) if above else (qy >= Y - 2))
                                    for j, (qx, qy) in enumerate(points) if j not in members)

        # Where a word may be lettered, in pixels from its dot (y down): above it, below it, to its right, to its left.
        # Lettering that could be read as a neighbour's stands a little off, with a tick from the dot to it.
        spots = []
        for above in (True, False):
            lead = crowded(above)
            space = 8.0 if lead else 3.0
            if above:
                dy = -(reach + space + lift + 0.3 * size)
            else:
                dy = reach + space + 0.8 * size
                if on_rule:
                    dy = max(dy, rule_y + 18 + 0.8 * size - Y)    # a word on the rule is lettered below its slashes
            spots.append((0.0, dy, "middle", lead))
        if rank <= 5:                                             # beside the dot only for the words that matter most
            spots += [(reach + 4, 0.35 * size, "start", False), (-(reach + 4), 0.35 * size, "end", False)]
        boxes = []
        for dx, dy, anchor, lead in spots:
            bx, by = X + dx, Y + dy
            left = {"middle": bx - width / 2, "start": bx - 2, "end": bx - width + 2}[anchor]
            boxes.append((dx, dy, anchor, lead, (left, by - size * 0.8, left + width, by + size * 0.3)))
        chosen = next((b for b in boxes if room.clear(*b[4]) and room.uncut(*b[4])), None)
        if chosen is None and rank <= 1:                      # the tip and the first word are lettered even across a line
            chosen = next((b for b in boxes if room.clear(*b[4])), None)
        if chosen is None:
            continue
        dx, dy, anchor, lead, spot = chosen
        pen.label(x + dx * px, y - dy * px, shown, size, ink, anchor)
        room.add(*spot)
        placed += 1
        if lead:                                              # the tick, from the dot's edge to the lettering
            way = -1.0 if dy < 0 else 1.0                     # up the page, or down it
            a = reach + 1.5 + (lift if dy < 0 else 0.0)
            b = (-dy - 0.3 * size if dy < 0 else dy - 0.8 * size) - 1.5
            pen.line(x, y - way * a * px, x, y - way * b * px, 2, LEADER)
    _notes(pen, rows, home, away, describe(body, seed, ctx))


def _layout(box, margin, count, top, longest) -> tuple:
    """(pixels to a word, a letter's height in words, pixels between rows): the scale settle() will choose.

    Reckoned beforehand, so that what is given in pixels (the gaps, the
    slashes, where the labels go) can be placed in the drawing's own units.
    Across, the longest row takes the plate's width, at most UNIT_PX to a
    word. Up, a letter is as tall as the rows have room for: at most 26 px
    (or a word's width, if that is more) and three words' width, and at
    least a quarter of a word's width. Only when even a quarter will not fit
    are the words drawn closer too. Where letters are tall and the plate
    has height to spare, the rows stand further apart (up to two
    letters), so that a row's highest words are not read as the row above's.
    """
    gap_px = 50.0 if count <= 4 else 40.0
    room_w = (box[2] - box[0]) - 40.0 - margin
    room_h = (box[3] - box[1]) - 80.0 - (count - 1) * gap_px
    s = max(1.0, min(UNIT_PX, (room_w - 18.0) / (longest + 0.8)))
    letter = min(max(26.0, s), 3.0 * s, max(1.0, room_h) / (count * top))
    if letter < 0.25 * s:
        s = max(1.0, 4.0 * letter)
    if count > 1:
        spare = max(0.0, room_h - count * top * letter) / (count - 1)
        gap_px = max(gap_px, min(2.0 * letter, gap_px + spare))
    return s, letter / s, gap_px


def _home_runs(words, away) -> list:
    """The seed words of a row, in runs of neighbours: [(first, last, radius of the circle round them, in px)].

    A run with a flower in it has a wider circle, so that the flower's own
    ring shows inside it.
    """
    runs, k = [], 0
    while k < len(words):
        if away(words[k][0]) != 0:
            k += 1
            continue
        last = k
        while last + 1 < len(words) and away(words[last + 1][0]) == 0:
            last += 1
        runs.append((k, last, 13.0 if any(words[j][1] for j in range(k, last + 1)) else 9.0))
        k = last + 1
    return runs


class _Room:
    """The crowded places of a plate, in pixels with y down: boxes no label may cover, and lines no label may cut.

    Filed in squares, so that asking about one label looks only at what lies
    near it. A label is drawn on a patch of clear paper, and where that patch
    cut a line between two words, the cut would read as a line break.
    """
    SQUARE = 48.0

    def __init__(self):
        self.boxes, self.strokes = {}, {}

    def _squares(self, x0, y0, x1, y1):
        q = self.SQUARE
        for i in range(int(math.floor(x0 / q)), int(math.floor(x1 / q)) + 1):
            for j in range(int(math.floor(y0 / q)), int(math.floor(y1 / q)) + 1):
                yield i, j

    def add(self, x0, y0, x1, y1) -> None:
        for key in self._squares(x0, y0, x1, y1):
            self.boxes.setdefault(key, []).append((x0, y0, x1, y1))

    def stroke(self, x1, y1, x2, y2) -> None:
        for key in self._squares(min(x1, x2), min(y1, y2), max(x1, x2), max(y1, y2)):
            self.strokes.setdefault(key, []).append((x1, y1, x2, y2))

    def clear(self, x0, y0, x1, y1) -> bool:
        """Does the box cover nothing already placed?"""
        for key in self._squares(x0, y0, x1, y1):
            for a0, b0, a1, b1 in self.boxes.get(key, ()):
                if not (x1 <= a0 or x0 >= a1 or y1 <= b0 or y0 >= b1):
                    return False
        return True

    def uncut(self, x0, y0, x1, y1, pad=2.5) -> bool:
        """Does the box, with the clear paper round its lettering, leave every line between words whole?"""
        near = (x0 - pad, y0 - pad, x1 + pad, y1 + pad)
        for key in self._squares(*near):
            for line in self.strokes.get(key, ()):
                if _crosses(line, near):
                    return False
        return True


def _crosses(line, box) -> bool:
    """Does a straight line (x1, y1, x2, y2) pass through a box (left, top, right, bottom)? (Liang and Barsky's clip.)"""
    (x1, y1, x2, y2), (a0, b0, a1, b1) = line, box
    dx, dy = x2 - x1, y2 - y1
    t0, t1 = 0.0, 1.0
    for p, q in ((-dx, x1 - a0), (dx, a1 - x1), (-dy, y1 - b0), (dy, b1 - y1)):
        if p == 0:
            if q < 0:
                return False
            continue
        t = q / p
        if p < 0:
            if t > t1:
                return False
            t0 = max(t0, t)
        else:
            if t < t0:
                return False
            t1 = min(t1, t)
    return t0 <= t1


def _rule(pen, x0, x1, y, temper, ink, px, row) -> None:
    """A row's rule, at 0 letters from home, in the texture of the plant's qualities.

    Plain for a plain drift; doubled (two thin lines) for a waxy leaf; broken
    into dashes for a brittle stem; stippled with fine dots for a downy leaf.
    """
    if temper.brittle:
        dash, gap = 9 * px, 6 * px
        x = x0
        while x < x1:
            if temper.leaf == "waxy":
                pen.line(x, y, min(x + dash, x1), y, 7, ink)
                pen.line(x, y, min(x + dash, x1), y, 3, "paper")
            else:
                pen.line(x, y, min(x + dash, x1), y, 3, ink)
            x += dash + gap
    elif temper.leaf == "waxy":
        pen.line(x0, y, x1, y, 7, ink)
        pen.line(x0, y, x1, y, 3, "paper")
    else:
        pen.line(x0, y, x1, y, 2, ink)
    if temper.leaf == "downy":
        x, k = x0, 0
        while x <= x1:
            lift = (3.5, -3.5, 5.5, -5.0, 2.5, -2.5)[(k + row) % 6] * px
            pen.line(x, y + lift, x, y + lift, 2, ink)
            x += 4 * px
            k += 1


def _notes(pen, rows, home, away, said) -> None:
    """Three lines for the caption: how much it has said, how far it has gone, and where its words came from."""
    pen.note(said)
    words = [w[0] for _, row in rows for w in row]
    if not words:
        return
    reach = max(away(w) for w in words)
    if reach == 0:
        pen.note("it has not yet left its seed")
        return
    farthest = next(w for w in words if away(w) == reach)
    beyond = reach >= TALLEST and any(away.far.get(w, 0) > TALLEST for w in words)
    text = "farthest from %s: %s, %s%d letter%s off" % (" / ".join(home), farthest[:WORD_MOST],
                                                       "more than " if beyond else "", reach, "" if reach == 1 else "s")
    start = len(home) if words[:len(home)] == home else 0      # the seed's own words, where it began, are not a return
    back = sum(1 for w in words[start:] if away(w) == 0)
    if back:
        text += " · came home %d time%s" % (back, "" if back == 1 else "s")
    pen.note(text)
    found = [w for w in words if w not in HOARD_SET and w not in home]       # one for each filled dot
    if not found:
        pen.note("every word so far is of its stock")
        return
    different = len(set(found))
    pen.note("%d of its words came from outside its stock" % len(found)
             + ("" if different == len(found) else " (%d different)" % different))


